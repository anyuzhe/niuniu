def fill(layout, d=None, d1=None, a=None):
    """把说明按卡片放进一个布局。"""
    for title, blocks in sections(d, d1, a):
        card = Card(title)
        for block in blocks:
            if block[0] == 'table':
                card.add(table(block[1], block[2]))
            else:
                card.add(label(block[1], 'note' if block[0] == 'note' else 'muted', True))
        layout.addWidget(card)
